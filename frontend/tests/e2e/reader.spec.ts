import { test, expect } from "@playwright/test";

test("read, paginate, navigate chapters, resize, and return to the library", async ({ page, context }, testInfo) => {
  const errors: string[] = [];
  const externalRequests: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("request", (request) => {
    if (request.url().includes("invalid.example")) externalRequests.push(request.url());
  });
  await page.goto("/");
  await page.getByLabel("Username", { exact: true }).fill("testowner");
  await page.getByLabel("Password", { exact: true }).fill("local-reader-test-only");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByRole("link", { name: /Read book\s*:\s*Reader fixture/ }).click();
  await expect(page.getByRole("button", { name: "Contents", exact: true })).toBeEnabled({ timeout: 45000 });
  await page.getByRole("button", { name: "Contents", exact: true }).click();
  await page.getByRole("complementary").getByRole("button", { name: "First chapter", exact: true }).click();
  const readingUrl = page.url();
  const frame = page.frameLocator(".epub-host iframe").first();
  await expect(frame.getByRole("heading", { name: "First chapter", exact: true })).toBeVisible();
  await expect(page.locator(".epub-host iframe").first()).toHaveAttribute("sandbox", /allow-same-origin/);
  await expect(frame.locator('meta[http-equiv="Content-Security-Policy"]')).toHaveAttribute("content", /script-src 'none'/);
  const publisherCodeRan = await frame.locator("body").evaluate((body) => {
    const doc = body.ownerDocument;
    const script = doc.createElement("script");
    script.textContent = "window.readerCspProbe = true";
    doc.body.append(script);
    const state = doc.defaultView as unknown as { readerCspProbe?: boolean; readerAttack?: number; svgAttack?: number };
    const ran = Boolean(state.readerCspProbe || state.readerAttack || state.svgAttack);
    script.remove();
    return ran;
  });
  expect(publisherCodeRan).toBe(false);
  await expect.poll(() => frame.getByAltText("Fixture illustration").evaluate((image) => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0);
  const status = page.locator(".reader-footer [role=status]");
  await expect(status).toContainText(/First chapter.*1 \//);
  const firstPage = await status.innerText();
  await page.getByRole("button", { name: "Next", exact: true }).click();
  await expect(status).not.toHaveText(firstPage);
  await page.getByRole("button", { name: "Contents", exact: true }).click();
  await page.getByRole("complementary", { name: "Table of contents" }).getByRole("button", { name: "Second chapter", exact: true }).click();
  await expect(frame.getByRole("heading", { name: "Second chapter", exact: true })).toBeVisible();
  await page.setViewportSize({ width: 844, height: 390 });
  await expect(frame.getByRole("heading", { name: "Second chapter", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("reader-landscape.png") });
  await page.getByRole("button", { name: "Contents", exact: true }).click();
  await page.getByRole("complementary", { name: "Table of contents" }).getByRole("button", { name: "First chapter", exact: true }).click();
  await expect(frame.getByRole("heading", { name: "First chapter", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Next", exact: true })).toBeEnabled();
  const internalLink = frame.getByRole("link", { name: "Internal chapter link", exact: true });
  if (testInfo.project.use.hasTouch) await internalLink.tap();
  else await internalLink.click();
  await expect(frame.getByRole("heading", { name: "Second chapter", exact: true })).toBeVisible();
  await page.getByRole("link", { name: "← Library", exact: true }).click();
  await expect(page.getByRole("link", { name: /Read book\s*:\s*Reader fixture/ })).toBeVisible();
  expect(externalRequests).toEqual([]);
  expect(errors).toEqual([]);
  await context.clearCookies();
  await page.goto(readingUrl);
  await expect(page.locator(".reader-error")).toContainText("Sign in from the library");
});
